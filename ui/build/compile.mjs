// Precompiles the console's templates into ui/render.js so the browser runs
// the runtime-only Vue build and the page needs no 'unsafe-eval' in its CSP.
//
// The HTML in ui/index.html stays the source of truth: the root template is
// the content of <div id="app">, the code editor's is <template id="tpl-code-editor">.
//
//   cd ui/build && npm ci && node compile.mjs
//
// UI_BUILD_MODULES may point at a directory holding node_modules (used to keep
// installs out of the repo checkout).
import { readFileSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const require = createRequire(
  process.env.UI_BUILD_MODULES ? join(process.env.UI_BUILD_MODULES, 'x.js') : import.meta.url,
);
const { compile } = require('@vue/compiler-dom');

const html = readFileSync(join(here, '..', 'index.html'), 'utf8');

function between(start, end) {
  const from = html.indexOf(start);
  const to = html.indexOf(end, from + start.length);
  if (from < 0 || to < 0) throw new Error(`index.html: cannot find ${start} .. ${end}`);
  return html.slice(from + start.length, to);
}

// <div id="app"> runs up to the last </div> before the code editor template.
const appSection = between('<div id="app" v-cloak>', '<template id="tpl-code-editor">');
const app = appSection.slice(0, appSection.lastIndexOf('</div>'));
const editor = between('<template id="tpl-code-editor">', '</template>');

function render(name, source) {
  const errors = [];
  const { code } = compile(source.trim(), {
    mode: 'function',
    prefixIdentifiers: true,
    hoistStatic: true,
    onError: (e) => errors.push(e.message),
  });
  if (errors.length) throw new Error(`${name}: ${errors.join('; ')}`);
  return `  ${name}: (function () {\n${code}\n  })(),`;
}

const out = `/* GENERATED by ui/build/compile.mjs from ui/index.html - do not edit. */
window.consoleRender = {
${render('app', app)}
${render('codeEditor', editor)}
};
`;
writeFileSync(join(here, '..', 'render.js'), out);
